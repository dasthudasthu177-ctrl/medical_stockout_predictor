function generateLocalHealthOfficerAnalysis(
  facility: any,
  medicines: any[],
  outbreakFactor: number,
  notes?: string
) {
  const criticalDrugs = medicines.filter((m) => m.daysRemaining <= 4);
  const highRiskDrugs = medicines.filter((m) => m.daysRemaining > 4 && m.daysRemaining <= 7);

  const topCriticalNames = criticalDrugs.map((m) => m.name).join(', ') || 'None';
  const topHighRiskNames = highRiskDrugs.map((m) => m.name).join(', ') || 'None';

  return `### 📋 District Health Logistics Advisory & Stockout Mitigation Directive
**Facility:** ${facility?.name || 'Chennai Regional PHC Network'}
**Epidemic & Monsoon Risk Factor:** ${outbreakFactor > 40 ? '⚠️ High Outbreak Wave (+' + outbreakFactor + '% burn rate)' : 'Normal Seasonal Variation'}

---

#### 1. 🚨 Critical Vulnerability Triage (< 4 Days Inventory)
- **Immediate Stockout Risk:** **${topCriticalNames}**
- **Root Cause:** Compounded by local outbreak surges and standard 48–72h replenishment lead times.
- **Patient Impact:** Without intervention, an estimated 80–120 outpatients per day will face denied essential treatment within 72 hours.

#### 2. 🔄 Inter-Facility Reallocation (Buffer Balancing)
- **Immediate Transfer:** Trigger regional inter-clinic transfer protocol from surplus facilities (e.g., Royapettah Central Store) to ${facility?.name || 'the affected PHC'}.
- **Target Quantities:** Move 300–500 units of critical fever and rehydration stock to bridge the 3-day window before warehouse shipment arrives.

#### 3. 📲 Supplier Dispatch Nudge (Distributor Action)
- **Distributor:** Tamil Nadu Medical Services & Regional Warehouse.
- **Dispatch Priority:** Tier-1 Emergency Expedite.
- **WhatsApp Nudge:** Direct automated PO generated with delivery window within 24 hours.

#### 4. 🌧️ Outbreak Signal Protocol
${outbreakFactor > 30 ? '- **Monsoon/Dengue Alert:** Vector-borne cases are trending upwards. Maintain minimum 14-day buffer stock for ORS, Paracetamol, and Artemether.' : '- Regular weekly reorder cycles sufficient. Keep routine 10-day safety stock.'}

*Generated by District Health Supply Chain AI Intelligence Engine.*`;
}

// 1. AI Stockout Analysis Endpoint
app.post('/api/gemini/analyze', async (req, res) => {
  try {
    const { facility, medicines, outbreakFactor = 30, notes = '' } = req.body;

    if (!ai) {
      const localResult = generateLocalHealthOfficerAnalysis(facility, medicines, outbreakFactor, notes);
      return res.json({
        analysis: localResult,
        source: 'local-intelligence-engine',
      });
    }

    const prompt = `You are a Public Health Supply Chain Officer and Epidemiologist for the Tamil Nadu Health System / District Primary Health Network.
Analyze the following real-time medicine inventory and stockout forecast:

Facility: ${facility?.name || 'Primary Health Center'} (${facility?.district || 'Chennai'})
Daily Outpatient Footfall: ${facility?.dailyFootfall || 240} patients/day
Seasonal Outbreak Factor (Monsoon/Flu surge index): +${outbreakFactor}%

Medicine Inventory & Days-to-Stockout:
${JSON.stringify(
  (medicines || []).map((m: any) => ({
    name: m.name,
    category: m.category,
    currentStock: m.currentStock,
    dailyBurnRate: m.dailyBurnRate,
    daysRemaining: m.daysRemaining,
    stockoutRiskScore: `${m.stockoutRiskScore}%`,
    riskLevel: m.riskLevel,
  })),
  null,
  2
)}

User / Officer Notes: ${notes || 'Generate immediate mitigation and reallocation advice.'}

Provide an authoritative, high-impact clinical supply chain briefing in markdown:
1. Executive Risk Summary: Identify the 2-3 most dangerous impending stockouts and clinical consequences.
2. Inter-Facility Stock Rebalancing: Recommended transfers from nearby surplus clinics.
3. Priority Supplier Nudge: Specific purchase order quantities and urgency tier for the distributor.
4. Preventative Outbreak Tactics: Actions to absorb the next 2-3 weeks of disease surge.

Keep the advice crisp, direct, and actionable for medical officers.`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: prompt,
    });

    return res.json({
      analysis: response.text || generateLocalHealthOfficerAnalysis(facility, medicines, outbreakFactor, notes),
      source: 'gemini-3.8-flash',
    });
  } catch (error: any) {
    console.error('Error generating AI analysis:', error);
    const fallback = generateLocalHealthOfficerAnalysis(
      req.body.facility,
      req.body.medicines,
      req.body.outbreakFactor,
      req.body.notes
    );
    return res.json({
      analysis: fallback,
      source: 'fallback-rules',
      error: error?.message,
    });
  }
});

